"""The digests that decide which monitor bytes this installation may run.

The monitor is built from the same source as this package and released with
it, so no human reviews its digests before the release ships. What stands in
for that review is where the digests live: the release pipeline generates a
module into this package, and that module is read only from inside the
installed package. Anyone who can change it can change the code that reads
it, so it carries exactly this artifact's own trust and needs no second
trust service at runtime. It is never fetched, never read from release
metadata, and never configurable.

A source checkout carries no such module, and nothing is assumed in its
place: with no pin, no monitor is verified and none is provisioned. The
repository's own development setup generates one for the monitor it builds,
and that pin says so. A pin that says so is accepted only by an installation
that is itself a development installation, so an installed release never
runs a monitor whose digest was minted on somebody's workstation.

The pin is also bound to one release version. There is no cross-version
fallback and no newest-available lookup: an installation provisions the
monitor built from its own source and version, or none.

Stdlib-only, and reads no service configuration.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from enum import StrEnum
from importlib import import_module
from importlib.metadata import Distribution, PackageNotFoundError
from typing import TYPE_CHECKING, Final, cast

from ._assets import monitor_archive_name, monitor_executable_name
from ._errors import MonitorError

if TYPE_CHECKING:
    from types import ModuleType

__all__ = [
    "MONITOR_PIN_INVALID",
    "MONITOR_PIN_UNRELEASED",
    "MONITOR_PIN_VERSION_MISMATCH",
    "MONITOR_TARGET_UNPINNED",
    "MONITOR_UNPINNED",
    "Installation",
    "MonitorPin",
    "MonitorPinError",
    "PinProvenance",
    "monitor_pin",
    "read_pin",
    "this_installation",
]

#: The generated module's name, inside this package and nowhere else. A
#: dotted name rather than a path: it resolves through the import system, so
#: it can only be answered by a module installed as part of this package.
PINS_MODULE: Final[str] = f"{__package__}._generated_pins"

#: The distribution this package is installed as, for the version the pin is
#: bound to and for judging how it was installed.
_DISTRIBUTION: Final[str] = "vaultspec-rag"

#: Machine-readable code for an installation that carries no generated pins:
#: a source checkout whose monitor has never been built here.
MONITOR_UNPINNED = "monitor_unpinned"
#: Machine-readable code for generated pins that cannot be read as pins: a
#: missing or ill-typed field, a value that is not a SHA256 digest, or an
#: archive digest with no executable digest beside it.
MONITOR_PIN_INVALID = "monitor_pin_invalid"
#: Machine-readable code for pins minted for a different release version than
#: the one installed. The monitor is version-coupled; nothing falls back.
MONITOR_PIN_VERSION_MISMATCH = "monitor_pin_version_mismatch"
#: Machine-readable code for development pins inside an installed release.
MONITOR_PIN_UNRELEASED = "monitor_pin_unreleased"
#: Machine-readable code for a target this release published no monitor for.
MONITOR_TARGET_UNPINNED = "monitor_target_unpinned"

_SHA256 = re.compile(r"\A[0-9a-f]{64}\Z")


class PinProvenance(StrEnum):
    """How the generated pins were produced, as they declare themselves."""

    #: Generated by the release pipeline from the finalized monitors it
    #: published for this version. The only provenance an installed release
    #: accepts.
    RELEASE = "release"
    #: Generated by this repository's own development setup, from a monitor
    #: it compiled on this machine. Accepted only by a development
    #: installation.
    DEVELOPMENT = "development"


@dataclass(frozen=True)
class MonitorPin:
    """The digests and names one target's monitor is admitted under.

    Attributes:
        provenance: How the digests were produced.
        version: The release version the monitor was built for.
        tag: The release tag that published it, empty for a development pin
            that no tag published.
        target: The target triple the digests belong to.
        archive_name: The monitor-only archive's filename.
        archive_sha256: The digest the archive is verified against before
            anything is extracted from it.
        executable_name: The one member extracted from the archive, by
            basename, and the name it is installed under.
        executable_sha256: The digest the executable is verified against
            before it is installed and again before every spawn.
    """

    provenance: PinProvenance
    version: str
    tag: str
    target: str
    archive_name: str
    archive_sha256: str
    executable_name: str
    executable_sha256: str


@dataclass(frozen=True)
class Installation:
    """What the running installation is, as the pin check needs to know it.

    Attributes:
        version: The installed distribution's version, or ``None`` when no
            distribution metadata exists, which is a checkout being imported
            directly.
        development: Whether this installation came from a local source tree
            rather than from a built release artifact.
    """

    version: str | None
    development: bool


class MonitorPinError(MonitorError):
    """The monitor digests this installation would use are not usable.

    Nothing here tells anyone to obtain, configure or point at a monitor:
    obtaining it is automatic, and a condition that stops it is reported as
    what it is.
    """


def this_installation() -> Installation:
    """Describe the installation this code is running as.

    A development installation is one installed from a local directory, which
    the installer records in its direct-URL metadata, or one with no
    distribution metadata at all, which is a checkout on the import path.
    Anything installed from a built artifact - a wheel from an index, a wheel
    file, a bundle's embedded wheel - is not one.
    """
    try:
        distribution = Distribution.from_name(_DISTRIBUTION)
    except PackageNotFoundError:
        return Installation(version=None, development=True)
    return Installation(
        version=distribution.version,
        development=_installed_from_a_directory(distribution),
    )


def _installed_from_a_directory(distribution: Distribution) -> bool:
    """Return whether *distribution* was installed from a local directory.

    Reads the direct-URL record the installer writes beside the metadata. A
    record naming a directory, editable or not, is a local source install. No
    record at all is an install from a package index. A record that cannot be
    parsed says nothing, and saying nothing means not a development install:
    the stricter answer is the safe one, because it is the one that refuses a
    development pin.
    """
    # Function-local: parsing this record is the only JSON this module reads,
    # and only for an installation that has the record at all.
    import json

    recorded = distribution.read_text("direct_url.json")
    if recorded is None:
        return False
    try:
        parsed = json.loads(recorded)
    except ValueError:
        return False
    return isinstance(parsed, dict) and "dir_info" in parsed


def monitor_pin(target: str) -> MonitorPin:
    """Return the pin admitting the monitor for *target* in this installation.

    Args:
        target: The target triple to look the digests up under.

    Raises:
        MonitorPinError: When this installation carries no generated pins,
            when they cannot be read as pins, when they were minted for
            another version, when development pins turn up inside an
            installed release, or when this release published no monitor for
            *target*.
    """
    return read_pin(_generated_pins(), target, this_installation())


def _generated_pins() -> ModuleType | None:
    """Import the generated pins module, or return ``None`` when there is none."""
    try:
        return import_module(PINS_MODULE)
    except ModuleNotFoundError:
        return None


def read_pin(
    pins: ModuleType | None, target: str, installation: Installation
) -> MonitorPin:
    """Admit *target*'s monitor digests from *pins*, or refuse them.

    Split from :func:`monitor_pin` so that what the pins say, what the
    installation is, and which target is wanted are three stated inputs
    rather than three ambient ones. :func:`monitor_pin` supplies this
    installation's own.

    Raises:
        MonitorPinError: As :func:`monitor_pin` documents.
    """
    if pins is None:
        raise MonitorPinError(
            MONITOR_UNPINNED,
            "This installation carries no monitor digests, so no monitor can "
            "be verified or obtained. A release carries them; a source "
            "checkout whose monitor has not been built here does not.",
        )
    provenance = _provenance(pins)
    version = _text(pins, "RELEASE_VERSION")
    tag = _text(pins, "RELEASE_TAG", required=False)
    archives = _digests(pins, "ARCHIVE_SHA256")
    executables = _digests(pins, "EXECUTABLE_SHA256")
    if archives.keys() != executables.keys():
        raise MonitorPinError(
            MONITOR_PIN_INVALID,
            "The monitor digests cover different targets for the archive and "
            "for the executable inside it, so a target could be fetched and "
            f"then never allowed to run: archives {sorted(archives)}, "
            f"executables {sorted(executables)}.",
        )
    _require_admissible(provenance, version, installation)
    if target not in archives:
        raise MonitorPinError(
            MONITOR_TARGET_UNPINNED,
            f"Release {version} published no monitor for {target}, so there "
            f"is no digest to admit one. It published {sorted(archives)}.",
        )
    return MonitorPin(
        provenance=provenance,
        version=version,
        tag=tag,
        target=target,
        archive_name=monitor_archive_name(version, target),
        archive_sha256=archives[target],
        executable_name=monitor_executable_name(target),
        executable_sha256=executables[target],
    )


def _require_admissible(
    provenance: PinProvenance, version: str, installation: Installation
) -> None:
    """Refuse pins this installation must not use.

    Two refusals, in the order that answers the more serious question first.
    Development digests are minted on a workstation from a monitor nobody
    published, so an installed release never accepts them whatever version
    they name. Then the version: the monitor is built from one release's
    source, and a digest from another release describes a different program.

    Raises:
        MonitorPinError: When the pins may not be used here.
    """
    if provenance is PinProvenance.DEVELOPMENT and not installation.development:
        raise MonitorPinError(
            MONITOR_PIN_UNRELEASED,
            "The monitor digests in this installation were generated from a "
            "locally built monitor, and this is an installed release, which "
            "runs only the monitor its own release published.",
        )
    installed = installation.version
    if installed is not None and installed != version:
        raise MonitorPinError(
            MONITOR_PIN_VERSION_MISMATCH,
            f"The monitor digests in this installation were generated for "
            f"release {version}, and the installed release is {installed}. "
            "The monitor is built from one release's source, so digests from "
            "another release describe a different program.",
        )


def _provenance(pins: ModuleType) -> PinProvenance:
    """Read how the pins declare they were produced.

    Raises:
        MonitorPinError: When the declaration is absent or is not one of the
            two things pins can be. An unrecognised provenance is refused
            rather than treated as the stricter one: it means the generated
            module and this reader disagree about the contract.
    """
    declared = _text(pins, "PROVENANCE")
    try:
        return PinProvenance(declared)
    except ValueError as exc:
        raise MonitorPinError(
            MONITOR_PIN_INVALID,
            f"The monitor digests declare a provenance of {declared!r}, which "
            "is not one this installation knows how to judge.",
        ) from exc


def _text(pins: ModuleType, field: str, *, required: bool = True) -> str:
    """Read a string *field* of the generated pins.

    Raises:
        MonitorPinError: When the field is absent and required, or is set to
            something that is not a string.
    """
    value = getattr(pins, field, None)
    if value is None and not required:
        return ""
    if not isinstance(value, str) or (required and not value):
        raise MonitorPinError(
            MONITOR_PIN_INVALID,
            f"The monitor digests carry no usable {field}, so nothing says "
            "what they are digests of.",
        )
    return value


def _digests(pins: ModuleType, field: str) -> dict[str, str]:
    """Read a target-to-digest mapping of the generated pins.

    Every value is required to be a lower-case hexadecimal SHA256. A digest
    in any other shape is refused here rather than carried to a comparison it
    could only ever fail, where it would read as a replaced artifact.

    Raises:
        MonitorPinError: When the mapping is absent, empty, or holds anything
            but target names against SHA256 digests.
    """
    value = getattr(pins, field, None)
    if not isinstance(value, dict) or not value:
        raise MonitorPinError(
            MONITOR_PIN_INVALID,
            f"The monitor digests carry no {field} mapping, so no artifact "
            "has a digest to be admitted under.",
        )
    digests: dict[str, str] = {}
    for target, digest in cast("dict[object, object]", value).items():
        if (
            not isinstance(target, str)
            or not target
            or not isinstance(digest, str)
            or not _SHA256.match(digest)
        ):
            raise MonitorPinError(
                MONITOR_PIN_INVALID,
                f"The monitor {field} mapping holds {target!r} against "
                f"{digest!r}, which is not a target named against a SHA256 "
                "digest.",
            )
        digests[target] = digest
    return digests
